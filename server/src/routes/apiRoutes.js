const router = require('express').Router();
const auth = require('../middleware/authenticateToken');
const role = require('../middleware/requireRole');
const validate = require('../middleware/validateBody');
const c = require('../controller/indexcont');
const mongoose = require('mongoose');
const validId = (req, res, next) => mongoose.isObjectIdOrHexString(req.params.id) ? next() : res.status(400).json({ message: 'Invalid ID' });
router.use(auth);
router.get('/incidents', c.getController.getData);
router.post('/incidents', role('admin', 'operator', 'user'), validate('incident'), c.addController.addData);
router.patch('/incidents/:id', role('admin', 'operator', 'user'), validate('incident'), c.putController.putData);
router.delete('/incidents', role('admin'), c.dropController.dropData);
router.delete('/incidents/:id', role('admin', 'operator', 'user'), validId, c.dropController.dropOneData);
router.post('/incidents/reorder', role('admin', 'operator', 'user'), require('../controller/reorder').reorder);
router.get('/settings', c.getNumpadController.getDataNumpad);
router.post('/settings', role('admin', 'operator'), validate('numpad'), c.addNumpadController.addDataNumpad);
router.patch('/settings/:id', role('admin', 'operator'), validate('numpad'), c.putNumpadController.putNumpadData);
router.delete('/settings', role('admin'), c.dropNumpadController.dropDataNumpad);
router.get('/observations', c.getObsOptionsController.getObsOptions);
router.post('/observations', role('admin', 'operator'), validate('observation'), c.addObsOptionsController.addObsOptions);
router.patch('/observations/:id', role('admin', 'operator'), validate('observation'), c.putObsOptionsController.putObsOptions);
router.delete('/observations/:id', role('admin', 'operator'), validId, c.dropObsOptionsController.dropOneObsOption);
router.delete('/observations', role('admin'), c.dropObsOptionsController.dropObsOptions);
router.get('/races/current', c.getRaceController.getLastRaceId);
router.get('/races', require('../controller/raceSessions').list);
router.post('/races/new', role('admin', 'operator'), require('../controller/raceSessions').createNext);
router.post('/races', role('admin', 'operator'), validate('race'), c.addRaceController.addRace);
module.exports = router;
